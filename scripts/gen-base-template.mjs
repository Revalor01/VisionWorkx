// Codegen: templates/base/** -> lib/apps/baseTemplate.generated.ts
//
// The generated-app base scaffold lives as real, reviewable files under
// templates/base/. This bakes them into an importable module so the deploy
// route (a serverless function) doesn't have to read the filesystem at
// runtime. Run after editing anything under templates/base/ and commit the
// result:
//
//   npm run gen:base
import { readFileSync, writeFileSync, readdirSync, statSync } from "fs";
import { join, relative } from "path";

const ROOT = new URL("..", import.meta.url).pathname;
const BASE_DIR = join(ROOT, "templates/base");
const OUT = join(ROOT, "lib/apps/baseTemplate.generated.ts");

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

const files = walk(BASE_DIR)
  .map((abs) => [relative(BASE_DIR, abs), readFileSync(abs, "utf8")])
  .sort(([a], [b]) => a.localeCompare(b));

const body = files
  .map(([path, content]) => `  ${JSON.stringify(path)}: ${JSON.stringify(content)},`)
  .join("\n");

writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/gen-base-template.mjs — do not edit by hand.
// Source of truth: templates/base/**  (run \`npm run gen:base\` after changes)

export const BASE_TEMPLATE_FILES: Record<string, string> = {
${body}
};
`,
);

console.log(`wrote ${OUT} — ${files.length} files:`);
for (const [p] of files) console.log(`  ${p}`);
